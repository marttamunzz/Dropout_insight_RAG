import os
from dotenv import load_dotenv

load_dotenv()


LLM_MODELS = {
    "gemini": {
        "label": "Google Gemini 2.5 Flash",
        "provider": "gemini",
        "model": "gemini-2.5-flash",
    },
    "groq": {
        "label": "Groq Llama 3.3 70B",
        "provider": "groq",
        "model": "llama-3.3-70b-versatile",
    },
}


def _get_required_env_var(name: str) -> str:
    value = os.getenv(name)

    if not value:
        raise ValueError(
            f"Missing environment variable: {name}. "
            f"Define it in the .env file."
        )

    return value


def generate_with_llm(
    prompt: str,
    model_key: str = "gemini",
    temperature: float = 0.2,
    max_tokens: int = 5000,
) -> str:
    if model_key not in LLM_MODELS:
        available = ", ".join(LLM_MODELS.keys())
        raise ValueError(
            f"Unknown model_key '{model_key}'. "
            f"Available models: {available}"
        )

    config = LLM_MODELS[model_key]
    provider = config["provider"]
    model = config["model"]

    if provider == "gemini":
        return _call_gemini(
            prompt=prompt,
            model=model,
            temperature=temperature,
            max_tokens=max_tokens,
        )

    if provider == "groq":
        return _call_groq(
            prompt=prompt,
            model=model,
            temperature=temperature,
            max_tokens=max_tokens,
        )

    raise ValueError(f"Unsupported provider: {provider}")


def _call_gemini(
    prompt: str,
    model: str,
    temperature: float,
    max_tokens: int,
) -> str:
    from google import genai
    from google.genai import types

    client = genai.Client(
        api_key=_get_required_env_var("GEMINI_API_KEY")
    )

    response = client.models.generate_content(
        model=model,
        contents=prompt,
        config=types.GenerateContentConfig(
            temperature=temperature,
            max_output_tokens=max_tokens,
            thinking_config=types.ThinkingConfig(
                thinking_budget=0
            ),
        ),
    )

    # Debug para saber si Gemini corta por tokens o por otra razón
    try:
        print("🧠 Gemini finish reason:", response.candidates[0].finish_reason)
    except Exception as e:
        print("⚠️ Could not read Gemini finish reason:", e)

    try:
        print("🧠 Gemini usage metadata:", response.usage_metadata)
    except Exception as e:
        print("⚠️ Could not read Gemini usage metadata:", e)

    # Extraer texto de forma robusta
    text = ""

    try:
        if response.text:
            text = response.text
    except Exception:
        pass

    if not text:
        try:
            parts = response.candidates[0].content.parts
            text = "".join(
                part.text
                for part in parts
                if hasattr(part, "text") and part.text
            )
        except Exception:
            text = ""

    print("🧠 Gemini generated text length:", len(text))

    if not text:
        return "No text was generated by Gemini."

    return text.strip()


def _call_groq(
    prompt: str,
    model: str,
    temperature: float,
    max_tokens: int,
) -> str:
    from groq import Groq

    client = Groq(
        api_key=_get_required_env_var("GROQ_API_KEY")
    )

    response = client.chat.completions.create(
        model=model,
        messages=[
            {
                "role": "user",
                "content": prompt,
            }
        ],
        temperature=temperature,
        max_tokens=max_tokens,
    )

    text = response.choices[0].message.content

    if not text:
        return "No text was generated by Groq."

    return text.strip()